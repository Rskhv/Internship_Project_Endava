CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(60) NOT NULL,
  avatar TEXT,
  language VARCHAR(32) NOT NULL DEFAULT 'English',
  maturity_rating VARCHAR(16) NOT NULL DEFAULT 'adult' CHECK (maturity_rating IN ('kids', 'teen', 'adult')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, name)
);
CREATE INDEX IF NOT EXISTS profiles_user_id_idx ON profiles(user_id);

CREATE TABLE IF NOT EXISTS content (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_key TEXT UNIQUE,
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  content_type TEXT NOT NULL CHECK (content_type IN ('movie', 'tv_show')),
  release_year SMALLINT CHECK (release_year BETWEEN 1800 AND 2200),
  maturity_rating VARCHAR(24),
  duration INTEGER CHECK (duration IS NULL OR duration > 0),
  poster_url TEXT,
  backdrop_url TEXT,
  featured BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS content_type_year_idx ON content(content_type, release_year DESC, id);
CREATE INDEX IF NOT EXISTS content_title_search_idx ON content USING GIN (to_tsvector('simple', title));

CREATE TABLE IF NOT EXISTS genres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS content_genres (
  content_id BIGINT NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  genre_id BIGINT NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
  PRIMARY KEY (content_id, genre_id)
);
CREATE INDEX IF NOT EXISTS content_genres_genre_idx ON content_genres(genre_id, content_id);

CREATE TABLE IF NOT EXISTS actors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS directors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS content_actors (
  content_id BIGINT NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  actor_id BIGINT NOT NULL REFERENCES actors(id) ON DELETE CASCADE,
  PRIMARY KEY (content_id, actor_id)
);
CREATE TABLE IF NOT EXISTS content_directors (
  content_id BIGINT NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  director_id BIGINT NOT NULL REFERENCES directors(id) ON DELETE CASCADE,
  PRIMARY KEY (content_id, director_id)
);

CREATE TABLE IF NOT EXISTS episodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_id BIGINT NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  season_number SMALLINT NOT NULL CHECK (season_number > 0),
  episode_number SMALLINT NOT NULL CHECK (episode_number > 0),
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  duration INTEGER CHECK (duration IS NULL OR duration > 0),
  UNIQUE (content_id, season_number, episode_number)
);

CREATE TABLE IF NOT EXISTS watch_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  content_id BIGINT NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  progress_percentage NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (progress_percentage BETWEEN 0 AND 100),
  last_watched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed BOOLEAN NOT NULL DEFAULT false,
  UNIQUE (profile_id, content_id)
);
CREATE INDEX IF NOT EXISTS watch_history_recent_idx ON watch_history(profile_id, completed, last_watched_at DESC);

CREATE TABLE IF NOT EXISTS subscription_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  resolution VARCHAR(24) NOT NULL,
  max_profiles SMALLINT NOT NULL CHECK (max_profiles > 0),
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS user_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plan_id BIGINT NOT NULL REFERENCES subscription_plans(id),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'expired', 'cancelled')),
  starts_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS user_subscriptions_user_idx ON user_subscriptions(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subscription_id BIGINT REFERENCES user_subscriptions(id) ON DELETE SET NULL,
  amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  payment_method_label VARCHAR(40) NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('succeeded', 'failed')),
  transaction_reference TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payments_user_idx ON payments(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  event_type VARCHAR(80) NOT NULL,
  entity_type VARCHAR(80),
  entity_id TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_logs_recent_idx ON audit_logs(created_at DESC);

CREATE TABLE IF NOT EXISTS schema_migrations (
  name TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
